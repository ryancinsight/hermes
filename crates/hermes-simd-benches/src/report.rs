use crate::criterion_results::BenchResult;
use crate::host::HostCapabilities;
use std::collections::BTreeMap;
use std::fmt::Write as _;

/// A benchmark parameter parsed from its Criterion value string.
///
/// The order is total: variants rank `Numeric` < `String` < `None`; `String`
/// payloads compare lexicographically; `Numeric` payloads compare by the
/// IEEE 754 `totalOrder` predicate ([`f64::total_cmp`]), so `-0.0` sorts
/// before `0.0`, a NaN with a clear sign bit sorts after every non-NaN
/// number, and a NaN with a set sign bit sorts before every non-NaN number.
/// Equality is `cmp == Equal`, so `==`, `PartialOrd` and `Ord` agree and
/// `==` is reflexive for NaN.
enum ParamValue {
    Numeric(f64),
    String(String),
    None,
}

impl ParamValue {
    const fn rank(&self) -> u8 {
        match self {
            Self::Numeric(_) => 0,
            Self::String(_) => 1,
            Self::None => 2,
        }
    }
}

impl Ord for ParamValue {
    fn cmp(&self, other: &Self) -> std::cmp::Ordering {
        match (self, other) {
            (Self::Numeric(a), Self::Numeric(b)) => a.total_cmp(b),
            (Self::String(a), Self::String(b)) => a.cmp(b),
            (Self::None, Self::None) => std::cmp::Ordering::Equal,
            (Self::Numeric(_) | Self::String(_) | Self::None, _) => {
                self.rank().cmp(&other.rank())
            }
        }
    }
}

impl PartialOrd for ParamValue {
    fn partial_cmp(&self, other: &Self) -> Option<std::cmp::Ordering> {
        Some(self.cmp(other))
    }
}

impl PartialEq for ParamValue {
    fn eq(&self, other: &Self) -> bool {
        self.cmp(other) == std::cmp::Ordering::Equal
    }
}

impl Eq for ParamValue {}

fn parse_param(value_str: Option<&str>) -> ParamValue {
    let Some(s) = value_str else {
        return ParamValue::None;
    };
    for prefix in ["density_", "sparsity_"] {
        if let Some(pct) = s.strip_prefix(prefix) {
            if let Some(num) = pct.strip_suffix("pct") {
                if let Ok(n) = num.parse::<f64>() {
                    return ParamValue::Numeric(n);
                }
            }
        }
    }
    s.parse::<f64>()
        .map_or_else(|_| ParamValue::String(s.to_string()), ParamValue::Numeric)
}

fn format_time(ns: f64) -> String {
    if ns < 1.0 {
        format!("{:.2} ps", ns * 1000.0)
    } else if ns < 1000.0 {
        format!("{ns:.2} ns")
    } else if ns < 1_000_000.0 {
        format!("{:.2} \u{03bc}s", ns / 1000.0)
    } else if ns < 1_000_000_000.0 {
        format!("{:.2} ms", ns / 1_000_000.0)
    } else {
        format!("{:.2} s", ns / 1_000_000_000.0)
    }
}

fn format_throughput(kind: &str, count: u64, ns: f64) -> String {
    let secs = ns / 1_000_000_000.0;
    if secs <= 0.0 {
        return "N/A".to_string();
    }
    let speed = count as f64 / secs;
    match kind {
        "Elements" if speed >= 1_000_000_000.0 => {
            format!("{:.3} Gelem/s", speed / 1_000_000_000.0)
        }
        "Elements" if speed >= 1_000_000.0 => {
            format!("{:.3} Melem/s", speed / 1_000_000.0)
        }
        "Elements" => format!("{speed:.3} Elem/s"),
        "Bytes" if speed >= 1_000_000_000.0 => {
            format!("{:.3} GB/s", speed / 1_000_000_000.0)
        }
        "Bytes" if speed >= 1_000_000.0 => format!("{:.3} MB/s", speed / 1_000_000.0),
        "Bytes" => format!("{speed:.3} B/s"),
        other => format!("{speed:.3} {other}/s"),
    }
}

pub(crate) fn render_markdown(
    results: &[BenchResult],
    cpu: &str,
    capabilities: HostCapabilities,
    generated_at: &str,
) -> String {
    let mut groups: BTreeMap<String, Vec<BenchResult>> = BTreeMap::new();
    for res in results {
        groups
            .entry(res.group_id.clone())
            .or_default()
            .push(res.clone());
    }

    let mut markdown = String::new();
    markdown.push_str("# Hermes SIMD Benchmark Results\n\n");
    let _ = writeln!(markdown, "- **CPU**: {cpu}");
    let _ = writeln!(
        markdown,
        "- **Runtime backend selected by dense dispatch**: `{}`",
        capabilities.runtime_backend()
    );
    let _ = writeln!(
        markdown,
        "- **Detected benchmark-relevant ISA features**: {}",
        capabilities.format_markdown()
    );
    let _ = writeln!(markdown, "- **Date**: {generated_at}");
    markdown.push('\n');
    markdown.push_str("This file is dynamically generated by the benchmark runner. Performance values represent point estimates computed by Criterion. ISA-specific rows only validate features detected on this host; unsupported AVX-512/AMX paths require a matching runner.\n\n");

    for (group_name, mut items) in groups {
        render_group(&mut markdown, &group_name, &mut items);
    }
    while markdown.ends_with("\n\n") {
        markdown.pop();
    }
    markdown
}

fn render_group(markdown: &mut String, group_name: &str, items: &mut [BenchResult]) {
    let _ = writeln!(markdown, "## {group_name}");
    markdown.push('\n');
    items.sort_by(|a, b| {
        let a_param = parse_param(a.value_str.as_deref());
        let b_param = parse_param(b.value_str.as_deref());
        match a_param.cmp(&b_param) {
            std::cmp::Ordering::Equal => a.function_id.cmp(&b.function_id),
            other => other,
        }
    });

    let has_params = items.iter().any(|item| item.value_str.is_some());
    let group_wide_baseline = group_wide_baseline(items);
    let baselines = parameter_baselines(items, group_wide_baseline.is_some());
    let has_speedup = group_wide_baseline.is_some() || !baselines.is_empty();
    render_header(markdown, has_params, has_speedup);

    for item in items {
        render_row(
            markdown,
            item,
            has_params,
            has_speedup,
            group_wide_baseline.as_ref(),
            &baselines,
        );
    }
    markdown.push('\n');
}

fn render_header(markdown: &mut String, has_params: bool, has_speedup: bool) {
    match (has_params, has_speedup) {
        (true, true) => {
            markdown
                .push_str("| Function | Parameter | Time | Throughput | Speedup vs Baseline |\n");
            markdown.push_str("|---|---|---|---|---|\n");
        }
        (true, false) => {
            markdown.push_str("| Function | Parameter | Time | Throughput |\n");
            markdown.push_str("|---|---|---|---|\n");
        }
        (false, true) => {
            markdown.push_str("| Function | Time | Throughput | Speedup vs Baseline |\n");
            markdown.push_str("|---|---|---|---|\n");
        }
        (false, false) => {
            markdown.push_str("| Function | Time | Throughput |\n");
            markdown.push_str("|---|---|---|\n");
        }
    }
}

fn render_row(
    markdown: &mut String,
    item: &BenchResult,
    has_params: bool,
    has_speedup: bool,
    group_wide_baseline: Option<&BenchResult>,
    baselines: &BTreeMap<String, BenchResult>,
) {
    let time_formatted = format_time(item.time_ns);
    let throughput_formatted = match (&item.throughput_kind, item.throughput_val) {
        (Some(kind), Some(val)) => format_throughput(kind, val, item.time_ns),
        _ => "N/A".to_string(),
    };
    let speedup_str = speedup_string(item, group_wide_baseline, baselines);

    match (has_params, has_speedup) {
        (true, true) => {
            let _ = writeln!(
                markdown,
                "| {} | {} | {} | {} | {} |",
                item.function_id,
                item.value_str.as_deref().unwrap_or("-"),
                time_formatted,
                throughput_formatted,
                speedup_str
            );
        }
        (true, false) => {
            let _ = writeln!(
                markdown,
                "| {} | {} | {} | {} |",
                item.function_id,
                item.value_str.as_deref().unwrap_or("-"),
                time_formatted,
                throughput_formatted
            );
        }
        (false, true) => {
            let _ = writeln!(
                markdown,
                "| {} | {} | {} | {} |",
                item.function_id, time_formatted, throughput_formatted, speedup_str
            );
        }
        (false, false) => {
            let _ = writeln!(
                markdown,
                "| {} | {} | {} |",
                item.function_id, time_formatted, throughput_formatted
            );
        }
    }
}

fn speedup_string(
    item: &BenchResult,
    group_wide_baseline: Option<&BenchResult>,
    baselines: &BTreeMap<String, BenchResult>,
) -> String {
    let param_key = item.value_str.clone().unwrap_or_else(|| "none".to_string());
    if let Some(base_item) = group_wide_baseline {
        return speedup_against(item, base_item);
    }
    baselines
        .get(&param_key)
        .map_or_else(|| "-".to_string(), |base| speedup_against(item, base))
}

fn speedup_against(item: &BenchResult, base_item: &BenchResult) -> String {
    if item.function_id == base_item.function_id {
        format!("1.00x (Baseline: {})", base_item.function_id)
    } else {
        format!("{:.2}x", base_item.time_ns / item.time_ns)
    }
}

fn group_wide_baseline(items: &[BenchResult]) -> Option<BenchResult> {
    let mut baseline = None;
    for item in items {
        if is_baseline_candidate(&item.function_id)
            && item.value_str.is_none()
            && baseline.as_ref().is_none_or(|existing: &BenchResult| {
                existing.function_id != "scalar_iter" && item.function_id == "scalar_iter"
            })
        {
            baseline = Some(item.clone());
        }
    }
    baseline
}

fn parameter_baselines(
    items: &[BenchResult],
    has_group_wide_baseline: bool,
) -> BTreeMap<String, BenchResult> {
    let mut baselines: BTreeMap<String, BenchResult> = BTreeMap::new();
    if has_group_wide_baseline {
        return baselines;
    }
    for item in items {
        let param_key = item.value_str.clone().unwrap_or_else(|| "none".to_string());
        if is_baseline_candidate(&item.function_id)
            && baselines.get(&param_key).is_none_or(|existing| {
                existing.function_id != "scalar_iter" && item.function_id == "scalar_iter"
            })
        {
            baselines.insert(param_key, item.clone());
        }
    }
    baselines
}

fn is_baseline_candidate(function_id: &str) -> bool {
    matches!(
        function_id,
        "scalar_iter" | "dense_sum" | "dense_dot" | "dense_masked" | "dense" | "dispatch"
    )
}

#[cfg(test)]
mod tests {
    use super::{format_throughput, parse_param, render_group, ParamValue};
    use crate::criterion_results::BenchResult;
    use std::cmp::Ordering;

    /// Quiet NaN with a clear sign bit (IEEE 754 binary64 `0x7ff8_0000_0000_0000`).
    const POSITIVE_NAN: f64 = f64::from_bits(0x7ff8_0000_0000_0000);
    /// The same NaN with the sign bit set.
    const NEGATIVE_NAN: f64 = f64::from_bits(0xfff8_0000_0000_0000);

    #[test]
    fn parses_density_and_sparsity_parameters_as_numbers() {
        assert!(matches!(
            parse_param(Some("density_10pct")),
            ParamValue::Numeric(10.0)
        ));
        assert!(matches!(
            parse_param(Some("sparsity_99pct")),
            ParamValue::Numeric(99.0)
        ));
    }

    #[test]
    fn formats_byte_throughput() {
        assert_eq!(format_throughput("Bytes", 1_000, 1_000.0), "1.000 GB/s");
    }

    #[test]
    fn param_value_orders_by_variant_then_payload() {
        let numeric = ParamValue::Numeric;
        let text = |s: &str| ParamValue::String(s.to_string());
        assert_eq!(numeric(1.0).cmp(&numeric(2.0)), Ordering::Less);
        assert_eq!(numeric(2.0).cmp(&numeric(2.0)), Ordering::Equal);
        assert_eq!(text("a").cmp(&text("b")), Ordering::Less);
        assert_eq!(numeric(1.0e9).cmp(&text("")), Ordering::Less);
        assert_eq!(text("z").cmp(&ParamValue::None), Ordering::Less);
        assert_eq!(ParamValue::None.cmp(&numeric(0.0)), Ordering::Greater);
        assert_eq!(ParamValue::None.cmp(&ParamValue::None), Ordering::Equal);
    }

    fn order_samples() -> Vec<ParamValue> {
        let mut samples: Vec<ParamValue> = [
            POSITIVE_NAN,
            NEGATIVE_NAN,
            f64::INFINITY,
            f64::NEG_INFINITY,
            0.0,
            -0.0,
            1.0,
            2.0,
            -2.0,
        ]
        .into_iter()
        .map(ParamValue::Numeric)
        .collect();
        samples.extend(["", "a", "b"].map(|s| ParamValue::String(s.to_string())));
        samples.push(ParamValue::None);
        samples
    }

    #[test]
    fn param_value_variant_rank_orders_numeric_string_none() {
        let samples = order_samples();
        for a in &samples {
            for b in &samples {
                let cross_variant = std::mem::discriminant(a) != std::mem::discriminant(b);
                if cross_variant {
                    assert_eq!(a.cmp(b), a.rank().cmp(&b.rank()));
                }
            }
        }
        assert_eq!(
            (
                ParamValue::Numeric(POSITIVE_NAN).rank(),
                ParamValue::String(String::new()).rank(),
                ParamValue::None.rank()
            ),
            (0, 1, 2)
        );
    }

    #[test]
    fn param_value_numeric_payload_follows_ieee_total_order() {
        let ascending = [
            NEGATIVE_NAN,
            f64::NEG_INFINITY,
            -2.0,
            -0.0,
            0.0,
            1.0,
            f64::INFINITY,
            POSITIVE_NAN,
        ];
        for (i, a) in ascending.iter().enumerate() {
            for (j, b) in ascending.iter().enumerate() {
                assert_eq!(
                    ParamValue::Numeric(*a).cmp(&ParamValue::Numeric(*b)),
                    i.cmp(&j),
                    "payload bits {:#x} against {:#x}",
                    a.to_bits(),
                    b.to_bits()
                );
            }
        }
    }

    #[test]
    fn param_value_order_laws_hold_with_nan_and_signed_zero() {
        let samples = order_samples();
        for a in &samples {
            assert!(a.eq(a), "reflexive equality");
            for b in &samples {
                assert_eq!(a.cmp(b), b.cmp(a).reverse(), "antisymmetry");
                assert_eq!(a == b, a.cmp(b) == Ordering::Equal, "eq iff cmp Equal");
                assert_eq!(a.partial_cmp(b), Some(a.cmp(b)), "partial_cmp is Some(cmp)");
                for c in &samples {
                    if a.cmp(b) != Ordering::Greater && b.cmp(c) != Ordering::Greater {
                        assert_ne!(a.cmp(c), Ordering::Greater, "transitivity");
                    }
                }
            }
        }
    }

    #[test]
    fn param_value_nan_is_distinct_from_numbers_and_equal_to_itself() {
        let nan = ParamValue::Numeric(POSITIVE_NAN);
        assert_eq!(nan.cmp(&ParamValue::Numeric(1.0)), Ordering::Greater);
        assert_eq!(ParamValue::Numeric(1.0).cmp(&nan), Ordering::Less);
        assert!(nan == ParamValue::Numeric(POSITIVE_NAN));
        assert!(ParamValue::Numeric(-0.0) != ParamValue::Numeric(0.0));
    }

    #[test]
    fn render_group_sorts_rows_with_a_nan_parameter_last() {
        let row = |value: &str| BenchResult {
            group_id: "g".to_string(),
            function_id: "f".to_string(),
            value_str: Some(value.to_string()),
            time_ns: 1.0,
            throughput_kind: None,
            throughput_val: None,
        };
        let mut items = ["4", "NaN", "1", "3", "2"].map(row);
        let mut markdown = String::new();
        render_group(&mut markdown, "g", &mut items);
        let order: Vec<&str> = items
            .iter()
            .map(|item| item.value_str.as_deref().expect("invariant: every row has a value"))
            .collect();
        assert_eq!(order, ["1", "2", "3", "4", "NaN"]);
    }
}
